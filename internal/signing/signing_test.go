// reference_vectors.json is produced by testdata/gen_reference_vectors.mjs
// using the trade frontend's own @msgpack/msgpack and viem dependencies with
// the same algorithm as lib/hyperliquidHash.ts + lib/hyperliquid.ts. It is an
// independent implementation, not output of this package.
type vectors struct {
	Key     string `json:"key"`
	Address string `json:"address"`
	Cases   []struct {
		ActionJSON   string  `json:"action_json"`
		Nonce        string  `json:"nonce"`
		Vault        *string `json:"vault"`
		Msgpack      string  `json:"msgpack"`
		ConnectionID string  `json:"connection_id"`
		Signature    string  `json:"signature"`
	} `json:"cases"`
}

func TestReferenceVectors(t *testing.T) {
	raw, err := os.ReadFile("testdata/reference_vectors.json")
	if err != nil {
		t.Fatal(err)
	}
	var v vectors
	if err := json.Unmarshal(raw, &v); err != nil {
		t.Fatal(err)
	}
	key, _ := hex.DecodeString(strings.TrimPrefix(v.Key, "0x"))
	signer, err := NewKeySigner(key)
	if err != nil {
		t.Fatal(err)
	}
	if signer.Address() != v.Address {
		t.Fatalf("address %s want %s", signer.Address(), v.Address)
	}
	for i, c := range v.Cases {
		packed, err := EncodeActionJSON(c.ActionJSON)
		if err != nil {
			t.Fatalf("case %d encode: %v", i, err)
		}
		if got := "0x" + hex.EncodeToString(packed); got != c.Msgpack {
			t.Errorf("case %d msgpack\n got %s\nwant %s", i, got, c.Msgpack)
		}
		nonce, _ := strconv.ParseUint(c.Nonce, 10, 64)
		vault := ""
		if c.Vault != nil {
			vault = *c.Vault
		}
		conn, _ := ActionHash(c.ActionJSON, vault, nonce)
		var signed SignedAction
		if vault == "" {
			signed, err = SignAction(signer, c.ActionJSON, nonce)
		} else {
			// Vault hashing is kept only to verify against the reference;
			// SignAction never signs vault-routed actions.
			signed.Signature, err = signer.SignDigest(AgentDigest(conn))
		}
		if err != nil {
			t.Fatal(err)
		}
		if got := "0x" + hex.EncodeToString(conn[:]); got != c.ConnectionID {
			t.Errorf("case %d connection id %s want %s", i, got, c.ConnectionID)
		}
		want := c.Signature
		gotSig := signed.Signature.R + strings.TrimPrefix(signed.Signature.S, "0x") +
			strconv.FormatUint(signed.Signature.V, 16)
		if gotSig != want {
			t.Errorf("case %d signature\n got %s\nwant %s", i, gotSig, want)
		}
		rec, err := RecoverAddress(AgentDigest(conn), signed.Signature)
		if err != nil || rec != v.Address {
			t.Errorf("case %d recovered %s err %v", i, rec, err)
		}
	}
}

// Changing any signed field (account/vault, nonce, payload byte, key order)
// must change the connection id, otherwise a signature could be replayed
// against a different intent.
func TestBindingSensitivity(t *testing.T) {
	base := `{"type":"order","orders":[{"a":0,"b":true,"p":"50000","s":"0.001","r":false,"t":{"limit":{"tif":"Gtc"}}}],"grouping":"na"}`
	h0, err := ActionHash(base, "", 1)
	if err != nil {
		t.Fatal(err)
	}
	variants := []struct {
		name, json, vault string
		nonce             uint64
	}{
		{"nonce", base, "", 2},
		{"vault", base, "0x1111111111111111111111111111111111111111", 1},
		{"size trailing zero", strings.Replace(base, `"0.001"`, `"0.0010"`, 1), "", 1},
		{"key order", `{"orders":[{"a":0,"b":true,"p":"50000","s":"0.001","r":false,"t":{"limit":{"tif":"Gtc"}}}],"type":"order","grouping":"na"}`, "", 1},
	}
	for _, v := range variants {
		h, err := ActionHash(v.json, v.vault, v.nonce)
		if err != nil {
			t.Fatalf("%s: %v", v.name, err)
		}
		if h == h0 {
			t.Errorf("%s: hash unchanged", v.name)
		}
	}
}

func TestEncodeRejectsAmbiguousInput(t *testing.T) {
	for _, in := range []string{
		`{"x":1.5}`,
		`{"x":1e3}`,
		`{"x":9007199254740993}`,
		`{"a":1,"a":2}`,
		`{"a":1} {}`,
		`{"a":`,
		`{"type":"x","1":true}`,
		`{"x":1.0}`,
		`{"x":-1e0}`,
	} {
		if _, err := EncodeActionJSON(in); err == nil {
			t.Errorf("EncodeActionJSON(%s) accepted", in)
		}
	}
}

// backend_l1_frontend_vectors.json is copied from
// account/src/pkg/hlsigning/testdata (generated by importing the real
// trade hyperliquid.ts/hyperliquidHash.ts). A second independent source
// covering int widths, map16/array16, unicode escapes, whitespace and -0.
func TestBackendFrontendVectors(t *testing.T) {
	raw, err := os.ReadFile("testdata/backend_l1_frontend_vectors.json")
	if err != nil {
		t.Fatal(err)
	}
	var v struct {
		Key   string `json:"key"`
		Cases []struct {
			Name         string `json:"name"`
			ActionJSON   string `json:"action_json"`
			Nonce        string `json:"nonce"`
			Msgpack      string `json:"msgpack"`
			ConnectionID string `json:"connection_id"`
			R            string `json:"r"`
			S            string `json:"s"`
			V            uint64 `json:"v"`
		} `json:"cases"`
	}
	if err := json.Unmarshal(raw, &v); err != nil {
		t.Fatal(err)
	}
	key, _ := hex.DecodeString(strings.TrimPrefix(v.Key, "0x"))
	signer, _ := NewKeySigner(key)
	if len(v.Cases) < 5 {
		t.Fatalf("expected at least 5 cases, got %d", len(v.Cases))
	}
	for _, c := range v.Cases {
		packed, err := EncodeActionJSON(c.ActionJSON)
		if err != nil {
			t.Errorf("%s: %v", c.Name, err)
			continue
		}
		if got := hex.EncodeToString(packed); got != strings.TrimPrefix(c.Msgpack, "0x") {
			t.Errorf("%s msgpack\n got %s\nwant %s", c.Name, got, c.Msgpack)
		}
		nonce, _ := strconv.ParseUint(c.Nonce, 10, 64)
		signed, err := SignAction(signer, c.ActionJSON, nonce)
		if err != nil {
			t.Fatal(err)
		}
		if signed.Signature.R != c.R || signed.Signature.S != c.S || signed.Signature.V != c.V {
			t.Errorf("%s signature mismatch: %+v", c.Name, signed.Signature)
		}
	}
}
