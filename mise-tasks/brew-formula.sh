#!/usr/bin/env bash
#MISE description="Render the Homebrew formula (Formula/oku.rb) for a release tag from its SHA256SUMS"
# Usage: mise run brew-formula <tag> <SHA256SUMS> > Formula/oku.rb
# Points at the GitHub Release archives oku_<tag>_<os>_<arch>.tar.gz (each holds oku_<tag>_<os>_<arch>/oku).
set -euo pipefail
tag="${1:?tag, e.g. v0.1.0}"
sums="${2:?path to SHA256SUMS}"
repo="${OKU_RELEASE_REPO:-oku-trade/oku-cli}"
version="${tag#v}"
sha() {
  local f="oku_${tag}_$1.tar.gz" s
  s="$(awk -v f="$f" '$2 == f || $2 == "*"f { print $1 }' "$sums")"
  [[ "$s" =~ ^[0-9a-f]{64}$ ]] || { echo "no sha256 for $f in $sums" >&2; exit 1; }
  echo "$s"
}
url() { echo "https://github.com/${repo}/releases/download/${tag}/oku_${tag}_$1.tar.gz"; }

cat <<EOF
# Generated by oku-cli mise-tasks/brew-formula.sh for ${tag}. Do not edit by hand.
class Oku < Formula
  desc "Oku command-line client"
  homepage "https://github.com/${repo}"
  version "${version}"

  on_macos do
    on_arm do
      url "$(url darwin_arm64)"
      sha256 "$(sha darwin_arm64)"
    end
    on_intel do
      url "$(url darwin_amd64)"
      sha256 "$(sha darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux_arm64)"
      sha256 "$(sha linux_arm64)"
    end
    on_intel do
      url "$(url linux_amd64)"
      sha256 "$(sha linux_amd64)"
    end
  end

  def install
    bin.install "oku"
    generate_completions_from_executable(bin/"oku", "completion")
    prefix.install "THIRD_PARTY_NOTICES" if File.exist?("THIRD_PARTY_NOTICES")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/oku version")
  end
end
EOF
