#!/usr/bin/env bash
# Render oku-bin AUR metadata from the published Linux archive checksums.
# Usage: aur-pkgbuild.sh <tag> <SHA256SUMS> <output-directory>
set -euo pipefail
tag="${1:?tag}"; sums="${2:?SHA256SUMS}"; out="${3:?output directory}"
[[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] || { echo 'semver tag required' >&2; exit 2; }
version="${tag#v}"
version="${version//-/_}"
maintainer_name="${AUR_GIT_NAME:-oku release bot}"
maintainer_email="${AUR_GIT_EMAIL:-oku-release-bot@users.noreply.github.com}"
[[ "$maintainer_name" != *$'\n'* && "$maintainer_email" != *$'\n'* ]] || { echo 'invalid maintainer identity' >&2; exit 2; }
sha() {
  local archive="oku_${tag}_linux_${1}.tar.gz" value
  value="$(awk -v f="$archive" '$2 == f || $2 == "*"f { print $1 }' "$sums")"
  [[ "$value" =~ ^[0-9a-f]{64}$ ]] || { echo "missing or duplicate checksum for $archive" >&2; exit 1; }
  printf '%s' "$value"
}
x64="$(sha amd64)"; arm="$(sha arm64)"
mkdir -p "$out"
cat > "$out/PKGBUILD" <<EOF
# Maintainer: ${maintainer_name} <${maintainer_email}>
# Generated by oku-cli mise-tasks/aur-pkgbuild.sh for ${tag}.
pkgname=oku-bin
pkgver=${version}
pkgrel=1
pkgdesc='Swap and bridge across 30+ chains and trade perps on Oku, from your terminal or your AI agent.'
arch=('x86_64' 'aarch64')
url='https://github.com/oku-trade/oku-cli'
license=('AGPL-3.0-only')
provides=('oku')
conflicts=('oku')
options=('!strip' '!debug')
source_x86_64=('oku_${tag}_linux_amd64.tar.gz::https://github.com/oku-trade/oku-cli/releases/download/${tag}/oku_${tag}_linux_amd64.tar.gz')
source_aarch64=('oku_${tag}_linux_arm64.tar.gz::https://github.com/oku-trade/oku-cli/releases/download/${tag}/oku_${tag}_linux_arm64.tar.gz')
sha256sums_x86_64=('${x64}')
sha256sums_aarch64=('${arm}')

package() {
  local cpu=amd64
  [[ "\$CARCH" == aarch64 ]] && cpu=arm64
  local dir="\$srcdir/oku_${tag}_linux_\$cpu"
  install -Dm755 "\$dir/oku" "\$pkgdir/usr/bin/oku"
  install -Dm644 "\$dir/LICENSE" "\$pkgdir/usr/share/licenses/oku-bin/LICENSE"
  install -d "\$pkgdir/usr/share/bash-completion/completions" "\$pkgdir/usr/share/zsh/site-functions" "\$pkgdir/usr/share/fish/vendor_completions.d"
  "\$dir/oku" completion bash > "\$pkgdir/usr/share/bash-completion/completions/oku"
  "\$dir/oku" completion zsh > "\$pkgdir/usr/share/zsh/site-functions/_oku"
  "\$dir/oku" completion fish > "\$pkgdir/usr/share/fish/vendor_completions.d/oku.fish"
  chmod 644 "\$pkgdir/usr/share/bash-completion/completions/oku" "\$pkgdir/usr/share/zsh/site-functions/_oku" "\$pkgdir/usr/share/fish/vendor_completions.d/oku.fish"
}
EOF
cat > "$out/.SRCINFO" <<EOF
pkgbase = oku-bin
	pkgdesc = Swap and bridge across 30+ chains and trade perps on Oku, from your terminal or your AI agent.
	pkgver = ${version}
	pkgrel = 1
	url = https://github.com/oku-trade/oku-cli
	arch = x86_64
	arch = aarch64
	license = AGPL-3.0-only
	provides = oku
	conflicts = oku
	options = !strip
	options = !debug
	source_x86_64 = oku_${tag}_linux_amd64.tar.gz::https://github.com/oku-trade/oku-cli/releases/download/${tag}/oku_${tag}_linux_amd64.tar.gz
	sha256sums_x86_64 = ${x64}
	source_aarch64 = oku_${tag}_linux_arm64.tar.gz::https://github.com/oku-trade/oku-cli/releases/download/${tag}/oku_${tag}_linux_arm64.tar.gz
	sha256sums_aarch64 = ${arm}

pkgname = oku-bin
EOF
