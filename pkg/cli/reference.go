package cli

import (
	"fmt"
	"io"
	"sort"
	"strings"

	urfave "github.com/urfave/cli/v3"
)

// WriteCommandReference emits the deterministic command reference from the
// same urfave command tree that dispatches the executable.
func WriteCommandReference(w io.Writer) error {
	var document strings.Builder
	writer := io.Writer(&document)
	app := &App{}
	root := app.commandTree("", false)
	if _, err := fmt.Fprint(writer, "# Oku CLI command reference\n\nGenerated by `make docs` from the urfave/cli command tree. Do not edit by hand.\n\n"); err != nil {
		return err
	}
	if err := writeReferenceFlags(writer, "Global options", root.Flags); err != nil {
		return err
	}
	commands := make([]*urfave.Command, 0)
	for _, command := range root.Commands {
		if len(command.Commands) == 0 {
			commands = append(commands, command)
			continue
		}
		for _, child := range command.Commands {
			commands = append(commands, &urfave.Command{Name: command.Name + " " + child.Name, Usage: child.Usage, Flags: child.Flags})
		}
	}
	// urfave generates the completion command during setup. Document the
	// supported static script generation entrypoints explicitly.
	commands = append(commands, &urfave.Command{Name: "completion bash|zsh|fish", Usage: "Print a shell completion script; no network or credential access"})
	sort.Slice(commands, func(i, j int) bool { return commands[i].Name < commands[j].Name })
	for _, command := range commands {
		if _, err := fmt.Fprintf(writer, "## `oku %s`\n\n%s\n\n", command.Name, command.Usage); err != nil {
			return err
		}
		if err := writeReferenceFlags(writer, "Options", command.Flags); err != nil {
			return err
		}
	}
	_, err := io.WriteString(w, strings.TrimRight(document.String(), "\n")+"\n")
	return err
}

func writeReferenceFlags(w io.Writer, title string, flags []urfave.Flag) error {
	if len(flags) == 0 {
		return nil
	}
	if _, err := fmt.Fprintf(w, "### %s\n\n| Flag | Description | Default |\n| --- | --- | --- |\n", title); err != nil {
		return err
	}
	for _, f := range flags {
		var usage, def string
		switch typed := f.(type) {
		case *urfave.StringFlag:
			usage, def = typed.Usage, typed.Value
		case *urfave.BoolFlag:
			usage, def = typed.Usage, fmt.Sprint(typed.Value)
		case *urfave.IntFlag:
			usage, def = typed.Usage, fmt.Sprint(typed.Value)
		case *urfave.Int64Flag:
			usage, def = typed.Usage, fmt.Sprint(typed.Value)
		case *urfave.DurationFlag:
			usage, def = typed.Usage, typed.Value.String()
		}
		usage = strings.ReplaceAll(usage, "|", "\\|")
		if _, err := fmt.Fprintf(w, "| `--%s` | %s | `%s` |\n", f.Names()[0], usage, def); err != nil {
			return err
		}
	}
	_, err := fmt.Fprintln(w)
	return err
}
